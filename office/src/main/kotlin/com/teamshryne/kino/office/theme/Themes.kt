package com.teamshryne.kino.office.theme

/**
 * A document design system.
 *
 * The model picks a theme instead of inventing CSS, so every export looks
 * deliberate and consistent: real type scale, measured spacing, and a palette
 * that works in print, on screen, and in Word/PowerPoint.
 */
data class OfficeTheme(
    val id: String,
    val label: String,
    val accent: String,
    val accentSoft: String,
    val ink: String,
    val inkSoft: String,
    val muted: String,
    val surface: String,
    val surfaceAlt: String,
    val border: String,
    val background: String,
    val positive: String,
    val negative: String,
    val warning: String,
    val sansFont: String,
    val serifFont: String,
    val monoFont: String,
    val sansStack: String,
    val serifStack: String,
    val monoStack: String,
    val headingScale: Double = 1.0,
    val ruleWeight: Int = 1,
    val dark: Boolean = false,
) {
    val headingFamily: String get() = serifStack
    val bodyFamily: String get() = sansStack
    val codeFamily: String get() = monoStack
}

