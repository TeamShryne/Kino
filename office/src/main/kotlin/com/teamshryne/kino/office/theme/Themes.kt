    fun byId(id: String?): OfficeTheme {
        if (id.isNullOrBlank()) return all.first()
        val needle = id.trim().lowercase()
        return all.firstOrNull { it.id == needle }
            ?: all.firstOrNull { it.label.lowercase() == needle }
            ?: all.first()
    }

    val ids: List<String> get() = all.map { it.id }
}
